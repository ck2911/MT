#!/usr/bin/env python3
"""Reproduce every table of the thesis, in thesis order, numbered as in the thesis.

This script is the "Do-file" of the thesis in the sense of the department's
checklist: one command that produces the tables presented in the thesis, and no
other tables, in the exact order in which they appear and numbered accordingly.

What it does
------------
1. (optional, ``--full-rebuild``) re-runs the complete empirical pipeline
   ``scripts/run_full_pipeline.py`` so that every canonical CSV in
   ``results/final/`` is re-estimated from the data files.
2. Runs ``LATEX/scripts/generate_thesis_tables.py``, which reads the canonical
   CSV outputs and writes the LaTeX tables that the thesis compiles.
3. Reads the thesis sources (``LATEX/main.tex`` and the chapter files) to
   determine the order and numbering of the tables exactly as LaTeX assigns
   them, cross-checks that against the last compiled list of tables, and
   writes one numbered file per thesis table to
   ``results/final/thesis_tables/`` together with ``MANIFEST.md``.
4. (optional, ``--pdf``) typesets all tables into one PDF,
   ``results/final/thesis_tables/thesis_tables.pdf``, using the thesis
   preamble and bibliography. Table notes that refer to a chapter or section
   of the thesis take its number from the compiled thesis, which is compiled
   first if it has not been compiled yet.

No estimation happens in this file. Every number comes from the canonical
pipeline outputs listed in the manifest.

Usage
-----
    python3 scripts/reproduce_thesis_tables.py            # tables from the shipped outputs
    python3 scripts/reproduce_thesis_tables.py --pdf      # ... plus one PDF with all tables
    python3 scripts/reproduce_thesis_tables.py --full-rebuild --pdf   # re-estimate everything first
"""

