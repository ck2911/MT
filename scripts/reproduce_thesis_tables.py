# --------------------------------------------------------------------------- helpers
def run(command: list[str], cwd: Path, env: dict[str, str] | None = None) -> None:
    print("$", " ".join(command))
    completed = subprocess.run(command, cwd=cwd, env=env)
    if completed.returncode != 0:
        sys.exit(f"command failed with exit code {completed.returncode}: {' '.join(command)}")


def strip_comments(text: str) -> str:
    return "\n".join(re.sub(r"(?<!\\)%.*$", "", line) for line in text.splitlines())


def inputs_in(tex_file: Path) -> list[str]:
    """Return the \\input{...} targets of a LaTeX file, in order, ignoring comments."""
    return re.findall(r"\\input\{([^}]+)\}", strip_comments(tex_file.read_text(encoding="utf-8")))


def table_inputs(tex_file: Path) -> list[str]:
    """Recursively collect \\input{tables/...} targets of a chapter file, in document order."""
    found: list[str] = []
    for target in inputs_in(tex_file):
        if target.startswith("tables/"):
            found.append(target.split("/", 1)[1])
            continue
        nested = LATEX / f"{target}.tex"
        if nested.exists():
            found.extend(table_inputs(nested))
    return found


def balanced_argument(text: str, start: int) -> str:
    """Return the content of the {...} group that starts at text[start] == '{'."""
    depth = 0
    for index in range(start, len(text)):
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : index]
    raise ValueError("unbalanced braces")


def caption_of(tex_file: Path) -> str:
    text = strip_comments(tex_file.read_text(encoding="utf-8"))
    match = re.search(r"\\caption\{", text)
    if not match:
        return ""
    caption = balanced_argument(text, match.end() - 1)
    caption = re.sub(r"\\(text|emph|textit|textbf)\{([^}]*)\}", r"\2", caption)
    return caption.replace("\\%", "%").replace("\\&", "&").strip()


def thesis_table_order() -> list[tuple[str, str]]:
    """Return [(thesis table number, LaTeX table file name), ...] in document order.

    Numbering follows LaTeX: tables are numbered <chapter>.<n> with the counter
    reset in every chapter, chapters are numbered in the order of \\mainmatter
    inputs in main.tex, and the appendix chapter is lettered.
    """
    main = strip_comments(MAIN_TEX.read_text(encoding="utf-8"))
    main_matter = main.split("\\mainmatter", 1)[1].split("\\backmatter", 1)[0]
    appendix = main.split("\\appendix", 1)[1] if "\\appendix" in main else ""
    chapters = re.findall(r"\\input\{(chapters/[^}]+)\}", main_matter)
    appendix_chapters = re.findall(r"\\input\{(chapters/[^}]+)\}", appendix)

    ordered: list[tuple[str, str]] = []
    for number, chapter in enumerate(chapters, start=1):
        for count, name in enumerate(table_inputs(LATEX / f"{chapter}.tex"), start=1):
            ordered.append((f"{number}.{count}", name))
    for letter_index, chapter in enumerate(appendix_chapters):
        letter = chr(ord("A") + letter_index)
        for count, name in enumerate(table_inputs(LATEX / f"{chapter}.tex"), start=1):
            ordered.append((f"{letter}.{count}", name))
    return ordered


def compiled_table_numbers() -> list[str] | None:
    if not LIST_OF_TABLES.exists():
        return None
    return re.findall(r"\\numberline \{([^}]+)\}", LIST_OF_TABLES.read_text(encoding="utf-8"))


# ---------------------------------------------------------------- standalone PDF
def ensure_thesis_compiled() -> None:
    """Compile the thesis once if it has never been compiled, so its labels can be reused."""
    if THESIS_AUX.exists():
        return
    latexmk = shutil.which("latexmk")
    if latexmk is None:
        print("latexmk not found on PATH: references to thesis chapters in table notes will show as ??.")
        return
    print("compiling the thesis once so that table notes can refer to its chapters and sections")
    run([latexmk, "main.tex"], cwd=LATEX)


def external_labels(entries: list[tuple[str, str, str]]) -> list[str]:
    """Labels that the table notes refer to but that are defined elsewhere in the thesis.

    They are copied from the compiled thesis (LATEX/build/main.aux) with the link
    target removed, so the standalone PDF prints the thesis numbers without
    pointing to pages that it does not contain.
    """
    if not THESIS_AUX.exists():
        return []
    text = "\n".join((OUT / filename).read_text(encoding="utf-8") for _n, _name, filename in entries)
    referenced = {
        label.strip()
        for group in re.findall(r"\\(?:[Cc]ref|ref|autoref)\{([^}]+)\}", text)
        for label in group.split(",")
    }
    defined = set(re.findall(r"\\label\{([^}]+)\}", text))
    needed = referenced - defined
    lines = []
    for line in THESIS_AUX.read_text(encoding="utf-8").splitlines():
        match = re.match(r"\\newlabel\{([^}]+)\}", line)
        if not match or match.group(1).removesuffix("@cref") not in needed:
            continue
        link = re.match(r"^(\\newlabel\{[^}]+\}\{\{.*?\}\{.*?\}\{.*?\}\{)[^}]*(\}\{\}\})$", line)
        lines.append(link.group(1) + link.group(2) if link else line)
    return [r"\makeatletter", *lines, r"\makeatother"] if lines else []


def write_standalone_tex(entries: list[tuple[str, str, str]], stamp: str) -> Path:
    lines = [
        r"\documentclass[12pt,a4paper]{report}",
        r"\input{preamble/metadata}",
        r"\input{preamble/packages}",
        r"\input{preamble/formatting}",
        r"\input{preamble/theoremstyles}",
        r"\input{preamble/commands}",
        r"\addbibresource{bibliography/references.bib}",
        *external_labels(entries),
        r"\begin{document}",
        r"\pagenumbering{arabic}",
        r"\chapter*{Tables of the Thesis}",
        r"\noindent\ThesisTitle. \ThesisType, \ThesisAuthor.\par\medskip",
        r"\noindent This document was written on " + stamp + r" by \texttt{scripts/reproduce\_thesis\_tables.py}. "
        r"It contains every table of the thesis, produced from the canonical pipeline outputs in "
        r"\texttt{results/final/}, in the order in which the tables appear in the thesis and with the same numbering. "
        r"The manifest next to this file records the source files behind each table.\par",
        r"\clearpage",
    ]
    for number, _name, filename in entries:
        lines += [
            f"% ---- Table {number}",
            r"\renewcommand{\thetable}{" + number + "}",
            r"\renewcommand{\theHtable}{" + number + "}",
            r"\input{" + filename + "}",
            r"\clearpage",
        ]
    lines.append(r"\end{document}")
    path = OUT / "thesis_tables.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def build_pdf(tex_path: Path) -> None:
    xelatex = shutil.which("xelatex")
    if xelatex is None:
        print("xelatex not found on PATH: skipping the PDF (the numbered .tex tables were written).")
        return
    import os

    env = dict(os.environ)
    env["TEXINPUTS"] = f".:{LATEX}//:" + env.get("TEXINPUTS", "")
    env["BIBINPUTS"] = f".:{LATEX}//:" + env.get("BIBINPUTS", "")
    latex = [xelatex, "-interaction=nonstopmode", "-halt-on-error", tex_path.name]
    run(latex, cwd=OUT, env=env)
    biber = shutil.which("biber")
    if biber is None:
        print("biber not found on PATH: citations in table notes will show as keys.")
    else:
        run([biber, tex_path.stem], cwd=OUT, env=env)
    for _ in range(2):  # two more passes so citations and cross-references between tables resolve
        run(latex, cwd=OUT, env=env)
    log = (OUT / f"{tex_path.stem}.log").read_text(encoding="utf-8", errors="replace")
    unresolved = re.findall(r"(?:Reference|Citation) [`']([^']+)' on page", log)
    for aux in OUT.iterdir():
        if aux.suffix in {".aux", ".log", ".out", ".toc", ".bcf", ".xml", ".xdv", ".gz", ".lot", ".lof", ".fls", ".bbl", ".blg"}:
            aux.unlink()
    if unresolved:
        sys.exit(f"unresolved references or citations in the tables PDF: {sorted(set(unresolved))}")
    print(f"wrote {OUT / 'thesis_tables.pdf'}")


# -------------------------------------------------------------------------- main
def main() -> int:
    parser = argparse.ArgumentParser(description="Reproduce the thesis tables in thesis order and numbering.")
    parser.add_argument("--full-rebuild", action="store_true", help="Re-run the complete empirical pipeline first.")
    parser.add_argument("--pdf", action="store_true", help="Also typeset all tables into one PDF.")
    parser.add_argument("--strict", action="store_true", help="Fail if the numbering disagrees with the last compiled thesis.")
    args = parser.parse_args()

    if args.full_rebuild:
        run([sys.executable, str(PIPELINE)], cwd=ROOT)
    run([sys.executable, str(TABLE_GENERATOR)], cwd=ROOT)

    ordered = thesis_table_order()
    unknown = [name for _n, name in ordered if name not in REGISTRY]
    if unknown:
        sys.exit(f"tables without registry entry (add them to REGISTRY): {unknown}")
    unused = sorted(set(REGISTRY) - {name for _n, name in ordered})
    if unused:
        sys.exit(f"registry entries that the thesis no longer uses: {unused}")

    if args.pdf:
        ensure_thesis_compiled()
    compiled = compiled_table_numbers()
    if compiled is None and args.strict:
        sys.exit("--strict needs the compiled thesis (LATEX/build/main.lot): compile it first with `cd LATEX && make pdf`")
    if compiled is not None and compiled != [number for number, _n in ordered]:
        message = f"numbering derived from the sources {[n for n, _ in ordered]} differs from the last compiled thesis {compiled}"
        if args.strict:
            sys.exit(message)
        print("WARNING:", message, "(recompile the thesis to refresh LATEX/build/main.lot)")

    # Start from an empty folder, but keep the tables PDF unless --pdf rewrites it.
    OUT.mkdir(parents=True, exist_ok=True)
    for path in OUT.iterdir():
        if path.is_file() and (args.pdf or path.name != "thesis_tables.pdf"):
            path.unlink()

    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    entries: list[tuple[str, str, str]] = []
    manifest = [
        "# Thesis tables",
        "",
        f"Written on {stamp} by `scripts/reproduce_thesis_tables.py`.",
        "",
        "Every table of the thesis, in the order in which it appears in the thesis and with the thesis numbering.",
        "The LaTeX files here are byte-identical to the files the thesis compiles from `LATEX/tables/`.",
        "",
        "| Table | Caption | File | Produced | Canonical inputs |",
        "|---|---|---|---|---|",
    ]
    for number, name in ordered:
        slug, produced, sources = REGISTRY[name]
        source = TABLES / f"{name}.tex"
        if not source.exists():
            sys.exit(f"missing table file {source}")
        filename = f"Table_{number}_{slug}.tex"
        shutil.copyfile(source, OUT / filename)
        entries.append((number, name, filename))
        inputs = "<br>".join(f"`{s}`" for s in sources) if sources else "none (registry of file paths)"
        manifest.append(f"| {number} | {caption_of(source)} | `{filename}` | {produced} | {inputs} |")
        print(f"Table {number:>4}  {filename}")
    manifest += [
        "",
        "Canonical inputs are produced by `python3 scripts/run_full_pipeline.py`.",
        "The thesis compiles these tables from `LATEX/tables/` via `cd LATEX && make pdf`.",
    ]
    (OUT / "MANIFEST.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print(f"wrote {OUT / 'MANIFEST.md'}")

    tex_path = write_standalone_tex(entries, stamp)
    if args.pdf:
        build_pdf(tex_path)
    else:
        print(f"wrote {tex_path} (run with --pdf to typeset it)")
    print(f"\n{len(entries)} thesis tables written to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
